#Take the price of three products and calculate the sum and average
product1_price=int(input("Enter product 1 price"))
product2_price=int(input("Enter product 2 price"))
product3_price=int(input("Enter product 3 price"))
sum=product1_price+product2_price+product3_price
average=(product1_price+product2_price+product3_price)/3
print("The sum of 3 products is",sum)
print(f"The sum of product is {sum}")
print("The average of 3 products is",average)
print(f"The average of product is {average}")




